#!/usr/bin/env node
// scripts/generate-sample-config.js
// ─────────────────────────────────────────────────────────────────────────────
// Reads STRIPE_PAYMENT_LINK and STRIPE_PUBLISHABLE_KEY from .env and writes
// samples/config.js — the only browser-safe config file for the sample page.
//
// Usage (run from project root):
//   node scripts/generate-sample-config.js
//
// Safe to run repeatedly — overwrites samples/config.js each time.
// NEVER writes secret keys (sk_… / whsec_…) to config.js.
// ─────────────────────────────────────────────────────────────────────────────

const fs   = require('fs');
const path = require('path');

const ROOT       = path.resolve(__dirname, '..');
const ENV_FILE   = path.join(ROOT, '.env');
const OUT_FILE   = path.join(ROOT, 'samples', 'config.js');

// ── Read .env ─────────────────────────────────────────────────────────────────
if (!fs.existsSync(ENV_FILE)) {
  console.error('Error: .env file not found at', ENV_FILE);
  console.error('Copy .env.example to .env and fill in your values first.');
  process.exit(1);
}

const envLines = fs.readFileSync(ENV_FILE, 'utf8').split('\n');
const env = {};
for (const line of envLines) {
  const trimmed = line.trim();
  if (!trimmed || trimmed.startsWith('#')) continue;
  const eqIdx = trimmed.indexOf('=');
  if (eqIdx === -1) continue;
  const key = trimmed.slice(0, eqIdx).trim();
  const val = trimmed.slice(eqIdx + 1).trim().replace(/^['"]|['"]$/g, '');
  env[key] = val;
}

// ── Validate and extract values ───────────────────────────────────────────────
const paymentLink    = env['STRIPE_PAYMENT_LINK']    || '';
const publishableKey = env['STRIPE_PUBLISHABLE_KEY'] || '';

// Payment Link is required.
if (!paymentLink || paymentLink.includes('REPLACE_WITH')) {
  console.error('Error: STRIPE_PAYMENT_LINK is not set in .env');
  console.error('Add it as: STRIPE_PAYMENT_LINK=https://buy.stripe.com/...');
  process.exit(1);
}

// Publishable key is optional — the sample page shows a placeholder if absent.
// Refuse to write a secret key if someone accidentally put it in the wrong var.
if (publishableKey.startsWith('sk_') || publishableKey.startsWith('whsec_')) {
  console.error('Error: STRIPE_PUBLISHABLE_KEY contains a secret key (sk_… or whsec_…).');
  console.error('Only publishable keys (pk_test_… or pk_live_…) are safe for the browser.');
  process.exit(1);
}

// ── Write samples/config.js ───────────────────────────────────────────────────
// publishableKey may be empty string — the sample page handles that gracefully.
const pkLine = publishableKey
  ? `  stripePublishableKey: ${JSON.stringify(publishableKey)},`
  : `  // stripePublishableKey not set — add STRIPE_PUBLISHABLE_KEY to .env`;

const output = `// samples/config.js  — AUTO-GENERATED by scripts/generate-sample-config.js
// Do not edit this file manually. Run: node scripts/generate-sample-config.js
// Only browser-safe values are written here. Secret keys are never included.

window.AJJ_SAMPLE_CONFIG = {
  // Stripe Payment Link — Stripe-hosted checkout page (Tab A).
  stripePaymentLink: ${JSON.stringify(paymentLink)},

  // Stripe publishable key — safe to expose in the browser (Tab B / Card form).
  // pk_live_ keys charge real money; use pk_test_ keys for development.
${pkLine}
};
`;

fs.writeFileSync(OUT_FILE, output, 'utf8');
console.log('✓ Written:', path.relative(ROOT, OUT_FILE));
console.log('  stripePaymentLink:    ', paymentLink);
console.log('  stripePublishableKey: ', publishableKey || '(not set)');
